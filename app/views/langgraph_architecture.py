import streamlit as st

from app.ai.graph import graph_mermaid
from app.components.erd import mermaid


def render(_f=None) -> None:
    st.title("LangGraph Architecture")
    st.caption("The diagram below is generated from the compiled graph in app/ai/graph.py. It is the real workflow.")
    code = graph_mermaid()
    mermaid(code, height=760)
    st.caption("Solid arrows = normal edges. Dotted arrows = conditional edges (a routing function decides).")
    with st.expander("Mermaid generated by LangGraph"):
        st.code(code, language="text")

    st.subheader("Concepts")
    st.markdown("""
- **LangGraph** is a library for building LLM applications as a **graph of steps** with explicit control flow
  (branches, loops, retries) instead of one big prompt.
- **StateGraph** is a graph whose steps share one typed **state** dictionary (`AnalystState` in `app/ai/state.py`).
- **Node** is a Python function `state -> partial update`. Example: `validate_sql` reads `generated_sql` and
  writes `validation_status`.
- **Edge** is a fixed "go next" link, e.g. `generate_sql → validate_sql`.
- **Conditional edge** is a routing function that picks the next node from the state, e.g. after `validate_sql`:
  valid → `execute_sql`, invalid with retries left → `generate_sql`, otherwise → `generate_response`.
- **Graph state** is the shared memory of one run: question, tables, SQL, results, errors, retry count and a
  `trace` list. `trace` uses a **reducer** (`operator.add`), so each node *appends* to it.
- **Execution** goes `START → understand_question → … → END`. LangGraph calls each node, merges its update into
  the state and asks the routing function where to go. `recursion_limit=25` is a hard stop on loops.
""")

    st.subheader("The 7 nodes")
    st.markdown("""
| # | Node | Uses LLM? | What it does |
|---|---|---|---|
| 1 | `understand_question` | ✅ | Turns the question into a precise objective; flags off-topic questions |
| 2 | `identify_tables` | ✅ | Chooses the minimum tables from the **live schema** and the join path |
| 3 | `generate_sql` | ✅ | Writes one PostgreSQL SELECT, using the business rules (revenue definition etc.). On retry it sees its previous SQL and the error |
| 4 | `validate_sql` | ❌ | Parses the SQL into a syntax tree (sqlglot) and checks it; enforces LIMIT |
| 5 | `execute_sql` | ❌ | Runs it as the read-only DB role in a READ ONLY transaction (5 s timeout) |
| 6 | `analyze_results` | ✅ | Explains **only the returned rows**, recommends a chart |
| 7 | `generate_response` | ❌ | Builds the final answer, or an honest error / "no data" message |
""")

    st.subheader("How SQL is kept safe (3 layers)")
    st.markdown("""
1. **Validator (Python):** the SQL is parsed, not keyword-matched. Rejects anything that isn't a single SELECT,
   any INSERT/UPDATE/DELETE/DROP/ALTER/TRUNCATE/COPY/SET anywhere in the tree (including inside CTEs),
   multiple statements, system tables (`pg_catalog`, `information_schema`), dangerous functions (`pg_sleep`,
   `pg_read_file`…), `SELECT INTO`, `FOR UPDATE`. Caps the result at 200 rows.
2. **Read-only transaction:** `SET TRANSACTION READ ONLY` before execution.
3. **Database permissions:** the `analytics_ro` role only has `SELECT` grants, default read-only sessions and a
   5-second `statement_timeout`. Even a query that slipped past layer 1 **cannot** write.
""")

    st.subheader("Example run: question → answer")
    st.markdown("""
**Question:** *"Which city generates the highest revenue?"*

1. `understand_question` → objective: *rank cities by revenue from processing/shipped/delivered orders*
2. `identify_tables` → `orders, customers` (join on `customer_id`)
3. `generate_sql` →
```sql
SELECT c.city, ROUND(SUM(o.total_amount), 2) AS revenue
FROM orders o JOIN customers c ON c.customer_id = o.customer_id
WHERE o.order_status IN ('processing','shipped','delivered')
GROUP BY c.city ORDER BY revenue DESC
```
4. `validate_sql` → ✅ valid, `LIMIT 200` added
5. `execute_sql` → 10 rows (Mumbai first)
6. `analyze_results` → findings + bar chart (x = city, y = revenue)
7. `generate_response` → final answer shown to the owner

Try it live on the **AI Business Analyst** page. Every step is shown as it runs.
""")
